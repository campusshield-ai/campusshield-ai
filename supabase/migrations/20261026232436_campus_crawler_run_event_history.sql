-- Owner-only crawl history used by the private CampusShield university web crawler.
-- The edge function accesses these tables with the server service role only.
create table if not exists public.campus_crawler_runs (
  id uuid primary key default gen_random_uuid(),
  started_by uuid not null references auth.users(id) on delete cascade,
  action text not null check (action in ('crawl_batch', 'crawl_university')),
  status text not null default 'queued'
    check (status in ('queued', 'running', 'completed', 'partial', 'failed')),
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  universities_requested integer not null default 0,
  pages_scanned integer not null default 0,
  office_pages_found integer not null default 0,
  fields_populated integer not null default 0,
  failed_or_blocked integer not null default 0,
  results jsonb not null default '[]'::jsonb
);

create table if not exists public.campus_crawler_events (
  id bigint generated by default as identity primary key,
  run_id uuid not null references public.campus_crawler_runs(id) on delete cascade,
  created_at timestamptz not null default now(),
  event_type text not null,
  university_id uuid,
  university_name text,
  page_url text,
  category text,
  status text,
  message text not null default '',
  metadata jsonb not null default '{}'::jsonb
);

create index if not exists campus_crawler_runs_started_at_idx
  on public.campus_crawler_runs (started_at desc);
create index if not exists campus_crawler_events_run_created_idx
  on public.campus_crawler_events (run_id, created_at asc);

alter table public.campus_crawler_runs enable row level security;
alter table public.campus_crawler_events enable row level security;

revoke all on table public.campus_crawler_runs from public, anon, authenticated;
revoke all on table public.campus_crawler_events from public, anon, authenticated;
grant all on table public.campus_crawler_runs to service_role;
grant all on table public.campus_crawler_events to service_role;
grant usage, select, update on sequence public.campus_crawler_events_id_seq to service_role;
